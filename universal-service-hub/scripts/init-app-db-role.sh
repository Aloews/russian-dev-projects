#!/bin/sh
set -eu

: "${PGHOST:?PGHOST is required}"
: "${PGUSER:?PGUSER is required}"
: "${PGDATABASE:?PGDATABASE is required}"
: "${PGPASSWORD:?PGPASSWORD is required}"
: "${USH_APP_DB_PASSWORD:?USH_APP_DB_PASSWORD is required}"

export PGPASSWORD
until pg_isready -h "$PGHOST" -p "${PGPORT:-5432}" -U "$PGUSER" -d "$PGDATABASE" >/dev/null 2>&1; do
  sleep 1
done

if psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -tAc "SELECT 1 FROM pg_roles WHERE rolname='ush_runtime'" | grep -q 1; then
  psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -v ON_ERROR_STOP=1 -c \
    "ALTER ROLE ush_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS"
else
  psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -v ON_ERROR_STOP=1 -c \
    "CREATE ROLE ush_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS"
fi

if psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -tAc "SELECT 1 FROM pg_roles WHERE rolname='ush_app'" | grep -q 1; then
  psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -v ON_ERROR_STOP=1 -c \
    "ALTER ROLE ush_app WITH LOGIN PASSWORD '$USH_APP_DB_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS"
else
  psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -v ON_ERROR_STOP=1 -c \
    "CREATE ROLE ush_app LOGIN PASSWORD '$USH_APP_DB_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS"
fi

psql -h "$PGHOST" -U "$PGUSER" -d "$PGDATABASE" -v ON_ERROR_STOP=1 -c \
  "GRANT ush_runtime TO ush_app; GRANT CONNECT ON DATABASE $PGDATABASE TO ush_app; GRANT USAGE, CREATE ON SCHEMA public TO ush_app; REASSIGN OWNED BY $PGUSER TO ush_app; GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO ush_app; GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO ush_app; ALTER DEFAULT PRIVILEGES FOR ROLE $PGUSER IN SCHEMA public GRANT ALL ON TABLES TO ush_app; ALTER DEFAULT PRIVILEGES FOR ROLE $PGUSER IN SCHEMA public GRANT ALL ON SEQUENCES TO ush_app"

echo "Created/verified non-superuser ush_app role with NOBYPASSRLS."
